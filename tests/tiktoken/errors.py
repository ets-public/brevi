# tiktoken's errors, with CPython's tiktoken's types and messages.
import tiktoken

enc = tiktoken.get_encoding("cl100k_base")


def t(label, f):
    try:
        r = f()
        print(label, "->", repr(r))
    except Exception as e:
        print(label, "!", type(e).__name__, repr(e))


t("disallowed", lambda: enc.encode("x <|endoftext|> y"))
t("disallowed2", lambda: enc.encode("<|fim_prefix|> <|endoftext|>", allowed_special={"<|endoftext|>"}))
t("disallowed str", lambda: enc.encode("<|endoftext|>", disallowed_special="<|endoftext|>"))
t("disallowed list", lambda: enc.encode("a <|endofprompt|>", disallowed_special=["<|endofprompt|>"]))
t("allowed list", lambda: enc.encode("hi", allowed_special=["<|endoftext|>"]))
t("allowed frozenset", lambda: enc.encode("<|endoftext|>", allowed_special=frozenset(["<|endoftext|>"])))
t("allowed both", lambda: enc.encode("<|endoftext|>", allowed_special={"<|endoftext|>"}, disallowed_special="all"))
t("allowed int", lambda: enc.encode("abc", allowed_special={1}))
t("allowed nonspecial", lambda: enc.encode("x<|endoftext|>", allowed_special={"<|endoftext|>", "nope"}))
t("partial special", lambda: enc.encode("<|endoftext", allowed_special="all"))
t("plain", lambda: enc.encode("<|endoftext|>", disallowed_special=()))
t("encode int", lambda: enc.encode(123))
t("encode bytes", lambda: enc.encode(b"x"))
t("encode None", lambda: enc.encode(None))
t("encode int plain", lambda: enc.encode(123, disallowed_special=()))
t("ordinary int", lambda: enc.encode_ordinary(123))
t("ordinary bytes", lambda: enc.encode_ordinary(b"ab"))
t("decode bad", lambda: enc.decode([999999]))
t("decode gap", lambda: enc.decode_bytes([100257, 100261]))
t("decode str", lambda: enc.decode("abc"))
t("decode int", lambda: enc.decode(5))
t("decode None", lambda: enc.decode(None))
t("decode float", lambda: enc.decode([1.5]))
t("decode strs", lambda: enc.decode(["a"]))
t("decode big", lambda: enc.decode([2**40]))
t("decode huge", lambda: enc.decode([2**70]))
t("decode neg", lambda: enc.decode([-1]))
t("decode range", lambda: enc.decode(range(3)))
t("decode tuple", lambda: enc.decode((1, 2)))
t("decode bool", lambda: enc.decode([True]))
t("decode strict", lambda: enc.decode([94], errors="strict"))
t("decode replace", lambda: enc.decode([94]))
t("decode ignore", lambda: enc.decode([94, 15339], errors="ignore"))
t("offsets bad utf8", lambda: enc.decode_with_offsets([94]))
t("single bad", lambda: enc.decode_single_token_bytes(999999))
t("single neg", lambda: enc.decode_single_token_bytes(-1))
t("single huge", lambda: enc.decode_single_token_bytes(2**70))
t("single str", lambda: enc.decode_single_token_bytes("a"))
t("encode single missing", lambda: enc.encode_single_token("notatoken"))
t("encode single int", lambda: enc.encode_single_token(5))
t("encode single bytes", lambda: enc.encode_single_token(b"\xff\xfe"))
t("is_special float", lambda: enc.is_special_token(1.0))
t("get_encoding unknown", lambda: tiktoken.get_encoding("foo"))
t("get_encoding int", lambda: tiktoken.get_encoding(5))
t("model unknown", lambda: tiktoken.encoding_for_model("foo"))
t("model name unknown", lambda: tiktoken.encoding_name_for_model("claude-3"))
t("same object", lambda: tiktoken.get_encoding("cl100k_base") is enc)
t("specials set cached", lambda: enc.special_tokens_set is enc.special_tokens_set)
t("specials", lambda: enc._special_tokens)
t("pattern", lambda: enc._pat_str)
t("ranks", lambda: (len(enc._mergeable_ranks), enc._mergeable_ranks[b"hello"], list(enc._mergeable_ranks.items())[:3]))
