# httpx: the module functions and Client, what they send, and what a Response holds
import json
import httpx

B = "http://127.0.0.1:18080"
S = "https://127.0.0.1:18081"
CERT = "tests/http/cert.pem"

r = httpx.get(B + "/echo?a=1", params={"b": "x y", "c": ["1", "2"], "n": 3, "t": True, "z": None}, headers={"X-Test": "1"})
print(r, r.status_code, r.reason_phrase, r.http_version, r.is_success, r.is_error, r.is_redirect, r.encoding)
print(r.url, repr(r.url), r.url.host, r.url.port, r.url.path, r.url.query, r.url.scheme, r.url.params)
print(r.headers)
print(r.headers["content-type"], r.headers.get("CONTENT-LENGTH"), "server" in r.headers, len(r.headers), list(r.headers.keys()), dict(r.headers))
print(r.json()["headers"])
print(r.request, r.request.method, r.request.url, r.request.headers)
print(r.history, r.next_request, r.links, r.num_bytes_downloaded, r.charset_encoding)
r = httpx.get(B + "/echo", params="raw=1&x=2")
print(r.url)
r = httpx.get(B + "/anything/x%20y/../z?q=a b&r=%7e")
print(r.url, r.json()["path"], r.json()["query"])

r = httpx.post(B + "/echo", data={"k": "v w", "n": 3, "l": ["a", "b"]})
print(r.json())
r = httpx.post(B + "/echo", json={"k": [1, 2], "s": "é", "f": 1.5})
print(r.json()["body"], r.json()["headers"][-2:])
r = httpx.post(B + "/echo", content="raw text body", headers={"Content-Type": "text/plain"})
print(r.json()["body"], r.json()["headers"][-2:])
r = httpx.post(B + "/echo", content=b"\x00\x01bytes")
print(r.json()["headers"][-1:])
r = httpx.put(B + "/echo", json=[1, None])
print(r.json()["method"], r.json()["body"])
r = httpx.patch(B + "/echo")
print(r.json()["method"], r.json()["headers"][-1])
r = httpx.delete(B + "/echo")
print(r.json()["method"], r.json()["headers"])
r = httpx.options(B + "/echo")
print(r.json()["method"])
r = httpx.head(B + "/echo")
print(r.status_code, r.text == "", r.headers["content-length"], r.content)
r = httpx.request("GET", B + "/echo", params={"q": "1"})
print(r.url)

# text and encodings
r = httpx.get(B + "/utf8")
print(r.encoding, repr(r.text), r.content)
r = httpx.get(B + "/latin1")
print(r.encoding, repr(r.text))
r = httpx.get(B + "/text-nocharset")
print(r.encoding, repr(r.text))
r = httpx.get(B + "/json-nocharset")
print(r.encoding, r.json())
r = httpx.get(B + "/empty")
print(r.status_code, r.reason_phrase, repr(r.text), r.content)
r = httpx.get(B + "/gzip")
print(r.headers["content-encoding"], r.text)
r = httpx.get(B + "/deflate")
print(r.json())
r = httpx.get(B + "/raw-deflate")
print(r.text)
r = httpx.get(B + "/chunked")
print(r.headers.get("transfer-encoding"), repr(r.text))
r = httpx.get(B + "/close")
print(repr(r.text))
r = httpx.get(B + "/big?gz=1")
print(len(r.content), r.content[1000:1005])
r = httpx.get(B + "/headers-out")
print(r.headers["x-multi"], r.headers.get_list("x-multi"), r.headers.multi_items()[-4:], r.links)
r = httpx.get(B + "/reason")
print(r.status_code, r.reason_phrase, r)
r = httpx.get(B + "/custom-reason")
print(r.status_code, r.reason_phrase, r)
print(httpx.codes.OK, httpx.codes.NOT_FOUND, httpx.codes.IM_A_TEAPOT, httpx.codes.get_reason_phrase(404), httpx.codes.is_success(204), httpx.codes(201), int(httpx.codes.CREATED))
r = httpx.get(B + "/lines")
print(list(r.iter_lines()), r.text.splitlines())

# Client
with httpx.Client(base_url=B, headers={"X-Client": "c"}, params={"cp": "1"}) as c:
    r = c.get("/echo", params={"rp": "2"}, headers={"X-Req": "r"})
    print(r.url, r.json()["headers"])
    r = c.get("cookies/set?flavor=oat&n=2")
    print(r.status_code, r.headers.get("location"), r.next_request, dict(c.cookies), r.cookies.get("flavor"))
    r = c.get("/cookies")
    print(r.json())
    r = c.get("/redirect/3", follow_redirects=True)
    print(r.status_code, r.url, [(h.status_code, str(h.url)) for h in r.history])
    r = c.get("/basic-auth/ann/pw", auth=("ann", "pw"))
    print(r.status_code, r.json())
    r = c.get("/basic-auth/ann/pw", auth=httpx.BasicAuth("ann", "bad"))
    print(r.status_code, r.is_client_error)
    print(c.base_url, c.headers["x-client"], c.is_closed)
print(c.is_closed)
c = httpx.Client(follow_redirects=True, auth=("ann", "pw"))
for code in [301, 302, 303, 307, 308]:
    r = c.post(B + "/redirect-to", params={"url": "/echo", "status": code}, content="payload")
    print(code, r.json()["method"], r.json()["body"], [h.status_code for h in r.history])
print(c.get(B + "/basic-auth/ann/pw").json())
r = c.get(B + "/absolute-redirect")
print(r.url)
c.close()
c = httpx.Client(max_redirects=2, follow_redirects=True)
try:
    c.get(B + "/redirect/5")
except httpx.TooManyRedirects as e:
    print("TooManyRedirects", e, e.request.url)

# HTTPS
r = httpx.get(S + "/echo?tls=1", verify=CERT)
print(r.status_code, r.url, r.json()["query"], r.json()["headers"][0])
with httpx.Client(verify=CERT) as c:
    print(c.get("https://localhost:18081/gzip").text.count("gzipped"))
print(httpx.get(S + "/echo", verify=False).status_code)
