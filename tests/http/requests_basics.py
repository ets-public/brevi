# requests: the module functions, what they send, and what a Response holds
import requests

B = "http://127.0.0.1:18080"

r = requests.get(B + "/echo?a=1", params={"b": "x y", "c": ["1", "2"], "d": None}, headers={"X-Test": "1"})
print(r, r.status_code, r.ok, bool(r), r.reason, r.url, r.encoding)
print(r.headers)
print(r.headers["content-type"], r.headers.get("CONTENT-LENGTH"), "server" in r.headers, len(r.headers))
print(r.json()["headers"])
print(r.request.method, r.request.url, r.request.path_url, r.request.headers)
print(r.history, r.is_redirect, r.links)

for m, f in [("post", requests.post), ("put", requests.put), ("patch", requests.patch)]:
    r = f(B + "/echo", data={"k": "v w", "n": 3})
    print(m, r.json())
r = requests.post(B + "/echo", json={"k": [1, 2], "s": "é"})
print(r.json()["body"], r.json()["headers"][-2:])
r = requests.post(B + "/echo", data="raw text body", headers={"Content-Type": "text/plain"})
print(r.json()["body"], r.json()["headers"][-2:])
r = requests.post(B + "/echo", data=b"\x00\x01bytes")
print(r.json()["headers"][-1:])
r = requests.post(B + "/echo", data=[("a", "1"), ("a", "2"), ("b", "3")])
print(r.json()["body"])
r = requests.delete(B + "/echo")
print(r.json()["method"], r.json()["headers"])
r = requests.options(B + "/echo")
print(r.json()["method"])
r = requests.head(B + "/echo")
print(r.status_code, r.text == "", r.headers["content-length"])
r = requests.request("GET", B + "/anything/x%20y/../z?q=a b&r=%7e")
print(r.url, r.json()["path"], r.json()["query"])
r = requests.get(B + "/echo", params="raw=1&x=2")
print(r.url)
r = requests.get(B + "/echo", params=[("a", 1), ("a", 2.5), ("u", "ü")])
print(r.url)

# text, content and encodings
r = requests.get(B + "/utf8")
print(r.encoding, repr(r.text), r.content)
r = requests.get(B + "/latin1")
print(r.encoding, repr(r.text), r.content)
r = requests.get(B + "/text-nocharset")
print(r.encoding, repr(r.text))
r.encoding = "utf-8"
print(repr(r.text))
r = requests.get(B + "/json-nocharset")
print(r.encoding, r.json(), r.apparent_encoding)
r = requests.get(B + "/html")
print(r.encoding, r.text)
r = requests.get(B + "/empty")
print(r.status_code, repr(r.text), r.content, r.ok)

# compressed and chunked bodies
r = requests.get(B + "/gzip")
print(r.headers["content-encoding"], r.text)
r = requests.get(B + "/deflate")
print(r.json())
r = requests.get(B + "/raw-deflate")
print(r.text)
r = requests.get(B + "/chunked")
print(r.headers.get("transfer-encoding"), repr(r.text))
r = requests.get(B + "/close")
print(repr(r.text))
r = requests.get(B + "/big")
print(len(r.content), r.content[:5], r.content[-5:])
r = requests.get(B + "/big?gz=1")
print(len(r.content), r.content[1000:1005])

# headers that repeat, reasons, status codes
r = requests.get(B + "/headers-out")
print(r.headers["x-multi"], r.headers["X-LOWER"], r.links)
print(r.links["next"]["url"])
r = requests.get(B + "/reason")
print(r.status_code, r.reason, r.ok)
r = requests.get(B + "/custom-reason")
print(r.status_code, r.reason, r.ok)
print(requests.codes.ok, requests.codes.NOT_FOUND, requests.codes.teapot, requests.codes["created"], requests.codes.get("nope"))
r = requests.get(B + "/lines")
print(list(r.iter_lines()))
print(r.iter_lines is not None)
