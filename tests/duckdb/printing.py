import duckdb
con = duckdb.connect()
# wide tables: shortening, pruning, expanding rows
cols = ", ".join(f"'value number {i} ' || repeat('x', {i})  as column_{i}" for i in range(14))
print(con.sql(f"select {cols} from range(3)"))
print(con.sql(f"select {cols} from range(30)"))
print(con.sql("select repeat('abcdefghij', 15) as long_text, 42 as n"))
print(con.sql("select repeat('abcdefghij', 15) as long_text, repeat('zz', 70) as other, 42 as n"))
print(con.sql("select repeat('abcdefghij', 15) as long_text, repeat('zz', 70) as other, 42 as n from range(25)"))
print(con.sql("select 'héllo wörld ' || range as s, '日本語テキスト' || range as j, range from range(4)"))
print(con.sql("select range as r, 'x' as s from range(24)"))
print(con.sql("select range as r from range(23)"))
print(con.sql("select range as r, range * 2 as d, 'a' as s from range(10)"))
print(con.sql("select range as r from range(10)"))
print(con.sql("select range as r from range(9)"))
print(con.sql("select null::int as a, null::varchar as b"))
print(con.sql("select 1 as \"weird name\", 2 as \"Upper\", 3 as \"tab\there\""))
con.sql("select * from range(3)").show(max_rows=2)
con.sql("select 'a' as x, null as y").show(null_value="∅")
con.sql(f"select {cols} from range(2)").show(max_width=200)
con.sql(f"select {cols} from range(2)").show(max_col_width=8)
print(con.sql("select [1, 2, 3] as l, {'a': 1, 'b': 'two'} as s, map {'k': 'v'} as m, [[1], [2, 3]] as ll"))
print(con.sql("select -1.5 as neg, 1e300 as big, 0.000001 as small, 12345.6789::decimal(10,4) as dec, 'nan'::double as nan"))
print(con.sql("select range % 3 as g, sum(range) as s from range(100) group by g order by g"))
print(con.sql("select * from range(0)"))
print(con.sql(f"select {cols} from range(0)"))
print(con.sql("select date '2026-11-07' as d, time '12:34:56' as t, timestamp '2026-11-07 12:34:56.789' as ts, interval 5 hour as i, true as b, 'x'::blob as bl"))
