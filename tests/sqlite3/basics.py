import sqlite3


def t(label, f):
    try:
        r = f()
        print(label, "ok", repr(r))
    except Exception as e:
        print(label, type(e).__name__, e, getattr(e, "sqlite_errorcode", None), getattr(e, "sqlite_errorname", None))


c = sqlite3.connect(":memory:")
t("multi", lambda: c.execute("select 1; select 2"))
