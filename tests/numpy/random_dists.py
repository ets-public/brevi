import numpy as np
g = np.random.default_rng(12345)
r = np.random.RandomState(7)
for o in (g, r):
    print(o.standard_gamma(0.5, 5))
    print(o.standard_gamma(3.0, 5))
    print(o.gamma(2.0, 3.0, size=4))
    print(o.beta(0.5, 0.7, 4), o.beta(2, 3, 4))
    print(o.chisquare(3, 4), o.f(3, 5, 3))
    print(o.standard_cauchy(3), o.standard_t(4, 3))
    print(o.vonmises(0.5, 2.0, 4))
    print(o.pareto(3, 3), o.weibull(1.5, 3), o.power(2, 3))
    print(o.laplace(1, 2, 3), o.gumbel(0, 1, 3), o.logistic(0, 1, 3))
    print(o.lognormal(0, 1, 3), o.rayleigh(2, 3), o.wald(1, 2, 3))
    print(o.triangular(0, 1, 3, 4))
    print(o.poisson(3.5, 8), o.poisson(50, 5), o.poisson([1, 20, 300]))
    print(o.binomial(10, 0.3, 8), o.binomial(1000, 0.4, 5), o.binomial(100, 0.9, 5), o.binomial(5, 0.0, 2), o.binomial(0, 0.5, 2))
    print(o.geometric(0.5, 6), o.geometric(0.05, 6))
    print(o.negative_binomial(3, 0.4, 6))
    print(o.zipf(2.0, 6), o.logseries(0.6, 6))
    print(o.hypergeometric(10, 15, 5, 6), o.hypergeometric(100, 200, 50, 6), o.hypergeometric(1000, 1000, 20, 4))
    print(o.multinomial(20, [0.2, 0.3, 0.5], size=3))
    print(o.dirichlet([1, 2, 3], 2), o.dirichlet([0.05, 0.02], 2))
    print(o.noncentral_chisquare(3, 2, 3), o.noncentral_chisquare(0.5, 2, 3), o.noncentral_f(3, 5, 1, 3))
    print(o.poisson(4), o.binomial(10, .5), o.gamma(2), o.normal([0, 10], [1, 2]))
    print(o.uniform(2, 5, 3), o.uniform([0, 1], 3), o.exponential(2, 3))
    print(o.normal(0, float('nan')), o.poisson(np.array([[1.0], [5.0]]), size=(2, 3)))
    for bad in [lambda: o.beta(0, 1), lambda: o.poisson(-1), lambda: o.geometric([0.5, 0]), lambda: o.triangular(1, 0, 2), lambda: o.normal([0, 1], 1, size=(2, 1)), lambda: o.normal([0, 1], 1, size=3), lambda: o.uniform(1, 0), lambda: o.multinomial(3, [0.9, 0.9]), lambda: o.hypergeometric(5, 5, 11), lambda: o.beta(1), lambda: o.binomial(np.array([5.5]), 0.5), lambda: o.negative_binomial(0, .5), lambda: o.dirichlet([-1, 1])]:
        try:
            print(bad())
        except Exception as e:
            print(type(e).__name__, e)
print(np.random.poisson(3, 2) is not None)
np.random.seed(5)
print(np.random.poisson(3, 4), np.random.binomial(9, 0.5, 4), np.random.gamma(2, 1, 2), np.random.beta(2, 2), np.random.standard_t(3))
