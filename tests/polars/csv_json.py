# CSV and JSON: inference, options, writing floats as polars does, files.
import polars as pl, io
df = pl.DataFrame({"f":[1.0, 1e20, 1e-7, 0.1, None, float("nan"), 123456789.0, -0.0], "s":["a,b",'q"x', "", None, "line\nx", " sp", "plain", "é"], "b":[True,False,None,True,True,True,True,False], "i":[1,None,3,4,5,6,7,8]})
print(repr(df.write_csv()))
print(repr(df.head(3).write_json()))
print(repr(df.head(3).write_ndjson()))
t = "a,b,c,d,e,f\n1,2.5,x,true,,\n2,,\"y,z\",False,,\n3,1e3,\"\",TRUE,,\n"
r = pl.read_csv(io.StringIO(t))
print(r, r.dtypes)
print(r["c"].to_list())
t2 = "a,a,b\n1,2,3\n"
print(pl.read_csv(io.StringIO(t2)).columns)
print(pl.read_csv(io.StringIO("x;y\n1;2\n"), separator=";"))
print(pl.read_csv(io.StringIO("1,2\n3,4\n"), has_header=False))
print(pl.read_csv(io.StringIO("a,b\n1,NA\n2,3\n"), null_values="NA"))
print(pl.read_json(io.StringIO('[{"a":1,"b":"x"},{"a":2,"b":null,"c":1.5}]')))
print(pl.read_ndjson(io.StringIO('{"a":1,"b":[1,2]}\n{"a":2,"b":[3]}\n')))
csv = """id,name,dept,salary,start
1,Alice,Eng,120000,2020-01-15
2,Bob,Sales,85000.50,2019-06-01
3,Carol,Eng,,2021-03-20
4,Dan,HR,70000,2018-11-11
5,Eve,Sales,92000,2022-02-02
"""
df = pl.read_csv(io.StringIO(csv))
print(df, df.schema)
df2 = pl.read_csv(io.StringIO(csv), schema_overrides={"salary": pl.Float32})
print(df2.dtypes)
print(pl.read_csv(io.StringIO(csv), columns=["name", "salary"]).head(2))
print(pl.read_csv(io.StringIO(csv), n_rows=2, skip_rows=0))
print(pl.read_csv(io.StringIO("a;b\n1;2\n3;4\n"), separator=";"))
print(pl.read_csv(io.StringIO("a,b\n1,NA\n3,4\n"), null_values="NA"))
out = df.group_by("dept").agg(pl.col("salary").mean().round(2).alias("avg"), pl.col("name").sort().first()).sort("dept")
print(out)
print(out.write_csv(), end="")
print(df.filter(pl.col("salary").is_null()).select("name"))
print(df.with_columns(pl.col("salary").fill_null(strategy="mean")))
print(df.select(pl.col("start").str.slice(0, 4).cast(pl.Int32).alias("year")).to_series().to_list())
print(df.select(pl.col("name").str.head(2), pl.col("name").str.tail(2).alias("t"), pl.col("dept").str.zfill(5)))
print(df.select(pl.col("name").str.extract(r"^(\w)", 1).alias("i"), pl.col("start").str.replace_all("-", "/")))
print(df.select(pl.col("name").str.count_matches("a"), pl.col("name").str.find("a").alias("f"), pl.col("name").str.reverse().alias("r")))
print(df.with_columns(pl.col("salary").cast(pl.Int64, strict=False)).dtypes)
print(df.select(pl.col("id").cast(pl.Utf8) + "-" + pl.col("dept")))
print(df.select(pl.format("{} works in {}", pl.col("name"), pl.col("dept")).alias("s")))
print(df.select(pl.col("salary").max() - pl.col("salary").min()), df.select((pl.col("salary") / 1000).floor().alias("k")))
print(df.select(pl.corr("id", "salary"), pl.cov("id", "salary").alias("cv")))
print(df.slice(1, 2), df.gather_every(2))
print(df.select(pl.int_range(0, pl.len()).alias("i"), "name"))
print(df.with_columns(pl.lit(None).alias("nothing"), pl.lit(3).alias("three"), pl.lit("s").alias("s"), pl.lit(2.5).alias("f")))
print(df.select(pl.col("salary").is_null().sum(), pl.col("name").count().alias("c"), pl.len()))
print(df.to_dicts()[0], df.row(1, named=True))
print(df.equals(df.clone()), df.select(pl.col("id").head(3)).to_series().to_list())
print(df.get_columns()[0].name)
print(df.select(pl.col("dept").unique(maintain_order=True)).to_series().to_list(), df["dept"].unique(maintain_order=True).to_list())
print(df["dept"].value_counts(sort=True, name="n"))
print(df.select(pl.when(pl.col("salary") > 90000).then(pl.lit("high")).otherwise(pl.col("dept")).alias("w")).to_series().to_list())
print(df.with_columns(pl.col("salary").rank("dense").alias("r"), pl.col("salary").rank("ordinal").alias("o")).select("r", "o").rows())
print(df.select(pl.col("salary").cum_max(), pl.col("id").cum_prod().alias("p")).rows())
print(df.with_columns(pl.col("salary").shift(1).over("dept").alias("prev")).select("dept", "prev").rows())
print(df.with_columns(pl.col("salary").sum().over("dept").alias("tot")).select("tot").to_series().to_list())
print(df.with_columns(pl.col("salary").mean().over("dept").alias("m")).select("m").to_series().to_list())
print(df.select(pl.col("name").sort_by("salary", descending=True, nulls_last=True)).to_series().to_list())
print(df.select(pl.col("name").filter(pl.col("dept") == "Eng")).to_series().to_list())
print(df.select(pl.col("salary").null_count(), pl.col("salary").n_unique().alias("u"), pl.col("salary").first().alias("f"), pl.col("salary").last().alias("l")))
print(df.drop_nulls().height, df.drop_nulls(subset=["name"]).height, df.unique().height)
print(df.select(pl.col("id").map_elements(lambda v: v * 10, return_dtype=pl.Int64)).to_series().to_list())
print(df["salary"].to_list(), df["id"].sum(), df["salary"].mean(), df.height)
print(df.with_columns(rate=pl.col("salary") * 1.1).select("rate").to_series().round(2).to_list())
