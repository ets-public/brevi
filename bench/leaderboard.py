"""Builds LEADERBOARD.md: tokens per finished task (code written plus errors read, retries scored as patches),
averaged over the current runs of each task set. usage: python3 leaderboard.py > LEADERBOARD.md"""
import json, collections

PY_BIG = ["p1b", "p2b", "p5b", "p6b", "p7b", "p8b"]
# (task set, model, {language: [runs]}). Each list is the runs on the current compiler, chosen when they were made.
SETS = [
    ("18 small tasks", "sonnet", {"brevi": ["s1", "s2"], "python": ["s1", "s2"]}),
    ("18 small tasks", "haiku", {"brevi": ["s1", "s2"], "python": ["s1", "s2"]}),
    ("8 big tasks", "sonnet", {"brevi": ["q1b", "q2b", "q3b"], "python": PY_BIG}),
    ("8 big tasks", "haiku", {"brevi": ["q1b", "q2b"], "python": PY_BIG}),
    ("6 held-out big tasks", "sonnet", {"brevi": ["n1", "n2"], "python": ["n1", "n2"]}),
    ("6 held-out big tasks", "haiku", {"brevi": ["n1", "n2"], "python": ["n1", "n2"]}),
    ("6 XL tasks (2 multi-file)", "sonnet", {"brevi": ["x17", "x18"], "python": ["x1", "x2", "x15", "x16"]}),
    ("6 XL tasks (2 multi-file)", "haiku", {"brevi": ["x17", "x18"], "python": ["x1", "x2", "x15", "x16"]}),
    ("6 held-out XL tasks (2 multi-file)", "sonnet", {"brevi": ["y1", "y2"], "python": ["y1", "y2"]}),
    ("6 held-out XL tasks (2 multi-file)", "haiku", {"brevi": ["y1", "y2"], "python": ["y1", "y2"]}),
]

def score(run):
    L = [json.loads(l) for l in open(f"logs/{run}.jsonl")]
    by = collections.OrderedDict()
    for r in L:
        if r["task"] != "_guide":  # guide lookups only add tokens read
            by.setdefault(r["task"], []).append(r)
    ok = lambda r: r["total"] > 0 and r["pass"] == r["total"]
    total = sum(r.get("patch_tok", r["code_tok"]) + r["out_tok"] for r in L)
    return total, sum(ok(t[0]) for t in by.values()), sum(ok(t[-1]) for t in by.values()), len(by)

print("# Leaderboard: tokens per finished task\n")
print("Lower is better. Each figure is the total tokens a model spends to finish every task in the set: the code it writes, the error output it reads, and each retry counted as the lines it changed. Counts are exact (count_tokens). Generated by `bench/leaderboard.py` from `bench/logs`.\n")
print("| Task set | Model | Brevi | Python | Brevi saves | First try (Brevi / Python) | Solved (Brevi / Python) | Runs |")
print("| --- | --- | --- | --- | --- | --- | --- | --- |")
for name, model, langs in SETS:
    row = {}
    for lang, runs in langs.items():
        s = [score(f"{r}-{model}-{lang}") for r in runs]
        row[lang] = (sum(x[0] for x in s) / len(s), sum(x[1] for x in s), sum(x[2] for x in s), sum(x[3] for x in s), len(s))
    b, p = row["brevi"], row["python"]
    save = (p[0] - b[0]) / p[0] * 100
    best = lambda v, o: f"**{v:,.0f}**" if round(v) < round(o) else f"{v:,.0f}"
    print(f"| {name} | {model.capitalize()} | {best(b[0], p[0])} | {best(p[0], b[0])} | {save:.0f}% | {b[1]}/{b[3]} / {p[1]}/{p[3]} | {b[2]}/{b[3]} / {p[2]}/{p[3]} | {b[4]} / {p[4]} |")
print("\nThe held-out tasks (`ref/gen_big2.py`) were written after the language was tuned and never used to change it. The XL tasks (`ref/gen_big3.py`, 150 to 400 lines, two of them split over several files) were held out until their first two runs (x1, x2); Brevi was then improved over six rounds for the gaps the runs showed (x3 to x18, so the XL set is no longer held out); the figures are the latest round (x17, x18) against four Python runs (x1, x2, x15, x16). A second XL set (`ref/gen_big4.py`, runs y1 and y2) was written after v0.18 and is held out. Single runs vary by up to 30%, so each figure averages two or more runs.")
