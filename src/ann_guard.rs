// The annotations CPython 3.13 evaluates when a statement runs (module and class `x: T`, and every def's
// parameter and return annotations, unless `from __future__ import annotations`), checked for the typed build,
// which never evaluates them: a file where one could raise (`def f(a: Later)` above `class Later`, `o: Vec`
// inside class Vec's own body, `Callable[int]`, `Union[()]`, `int[str]`, `"x" | int`) goes to the dynamic
// build, which evaluates them as CPython does. An annotation passes only when every name in it is bound on every
// path to it, and each subscript and `|` in it is one CPython 3.13 takes for the values those names can hold
// (src/pynames/ann_types.txt, generated by tools/gen_ann_types.py). Anything else (a call, a name imported from
// a local module inside a subscript, a program's own generic class subscripted) is not proven, and leaves too.
use crate::dynpy::parse::{Ex, FuncDef, St, Stmt};
use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

const TABLE: &str = include_str!("pynames/ann_types.txt");
const BUILTINS: &str = include_str!("pynames/builtins.txt");
const MODS: &str = include_str!("pynames/mods.txt");

// What a name or expression holds, as far as an annotation can use it.
#[derive(Clone, Debug, PartialEq)]
enum K {
    // a class or typing object of a stdlib module: module, name (a row of TABLE)
    Std(&'static str, &'static str),
    // a class the program makes with `class` (bases known, no metaclass): `|` and typing arguments work, a
    // subscript is not proven
    Class,
    // a class the program makes on `Generic[T, ...]` (or Protocol[...]) with that many type parameters, and no
    // other generic base: its subscript takes exactly as many typing arguments
    Generic(usize),
    // a class whose bases are not known (its metaclass could define `|`): a typing argument only
    ClassU,
    // a TypeVar (`T = TypeVar("T")`, or a PEP 695 `def f[T]` parameter)
    TVar,
    // a ParamSpec, TypeVarTuple, NewType, or a type alias (`int | None`, `List[int]`): `|` and typing arguments work
    Type,
    Module(String),
    // a name `from m import n` binds that is not in the table (a function, a constant, a local module's class)
    From(String, String),
    // anything else: the name is bound, nothing more is known
    Other,
}

impl K {
    fn ors(&self) -> bool {
        match self {
            K::Std(m, n) => flags(m, n).contains('o'),
            K::Class | K::Type | K::TVar | K::Generic(_) => true,
            _ => false,
        }
    }
    fn arg(&self) -> bool {
        match self {
            K::Std(m, n) => flags(m, n).contains('a'),
            K::Class | K::ClassU | K::Type | K::TVar | K::Generic(_) => true,
            _ => false,
        }
    }
}

fn flags(m: &str, n: &str) -> &'static str {
    tables().rows.get(&format!("{m} {n}")).map_or("-", |r| r.2)
}

struct Tables {
    // "module name" -> (module, name, flags, subscript)
    rows: HashMap<String, (&'static str, &'static str, &'static str, &'static str)>,
    mods: HashSet<&'static str>,
    builtins: HashSet<&'static str>,
}

fn tables() -> &'static Tables {
    static T: OnceLock<Tables> = OnceLock::new();
    T.get_or_init(|| {
        let mut rows = HashMap::new();
        let mut mods: HashSet<&'static str> = MODS.split_whitespace().collect();
        for l in TABLE.lines().filter(|l| !l.starts_with('#')) {
            let p: Vec<&'static str> = l.split(' ').collect();
            if let [m, n, f, s] = p[..] {
                rows.insert(format!("{m} {n}"), (m, n, f, s));
                mods.insert(m);
            }
        }
        Tables { rows, mods, builtins: BUILTINS.split_whitespace().collect() }
    })
}

#[derive(Clone, Default)]
struct Scope {
    names: HashMap<String, K>,
    class: bool,
    // how many statements of the scope bind each name (bound_in): a name bound once keeps its kind for the defs
    // inside the scope, whose bodies run later
    counts: HashMap<String, usize>,
}

struct Ctx {
    // names declared global or nonlocal anywhere: never taken as bound
    loose: HashSet<String>,
}

type Res = Result<(), (usize, String)>;

// The first annotation CPython evaluates that the typed build cannot be sure evaluates without raising, with why.
pub fn check(body: &[Stmt]) -> Option<(usize, String)> {
    if body.iter().any(|s| matches!(&s.st, St::ImportFrom(m, v) if m == "__future__" && v.iter().any(|(n, _)| n == "annotations"))) {
        return None;
    }
    let mut loose = HashSet::new();
    let mut reflective = false;
    scan_all(body, &mut |st| match st {
        St::Global(v) | St::Nonlocal(v) => loose.extend(v.iter().cloned()),
        _ => {}
    });
    crate::dynpy::typing::walk_all(body, &mut |e, _| {
        if matches!(e, Ex::Name(n) if matches!(n.as_str(), "globals" | "locals" | "vars" | "__builtins__" | "builtins")) {
            reflective = true;
        }
    });
    let mut first_ann = None;
    scan_all(body, &mut |st| {
        if first_ann.is_none() {
            first_ann = match st {
                St::AnnAssign(_, _, _, _) => Some(()),
                St::Def(d) if !d.params.ann.is_empty() || d.ret.is_some() => Some(()),
                _ => None,
            };
        }
    });
    first_ann?;
    if reflective {
        let line = body.first().map_or(1, |s| s.line);
        return Some((line, "annotations CPython evaluates, in a file that reaches its names through globals(), locals(), vars() or builtins".into()));
    }
    let cx = Ctx { loose };
    let mut top = Scope::default();
    bound_in(body, &mut top.counts);
    let mut chain = vec![top];
    cx.block(body, &mut chain, Where::Module).err()
}

#[derive(Clone, Copy, PartialEq)]
enum Where {
    Module,
    Class,
    Func,
}

// Every statement, nested blocks and def and class bodies included.
fn scan_all(body: &[Stmt], f: &mut dyn FnMut(&St)) {
    for s in body {
        f(&s.st);
        crate::typed_guard::each_block(&s.st, &mut |b| scan_all(b, f));
    }
}

// The names a block binds in its own scope (not in the defs and classes it holds), each with how many times.
fn bound_in(body: &[Stmt], out: &mut HashMap<String, usize>) {
    fn targets(t: &Ex, out: &mut HashMap<String, usize>) {
        match t {
            Ex::Name(n) => *out.entry(n.clone()).or_default() += 1,
            Ex::Tuple(v) | Ex::List(v) => v.iter().for_each(|x| targets(x, out)),
            Ex::Star(x) => targets(x, out),
            _ => {}
        }
    }
    for s in body {
        walrus_names(&s.st, &mut |n| *out.entry(n.to_string()).or_default() += 1);
        match &s.st {
            St::Assign(ts, _) => ts.iter().for_each(|t| targets(t, out)),
            St::AugAssign(t, _, _) | St::AnnAssign(t, Some(_), _, _) | St::For(t, _, _, _) => targets(t, out),
            St::Del(v) => v.iter().for_each(|t| targets(t, out)),
            St::Def(d) => *out.entry(d.name.clone()).or_default() += 1,
            St::Class(c) => *out.entry(c.name.clone()).or_default() += 1,
            St::Import(v) => {
                for (m, a) in v {
                    *out.entry(a.clone().unwrap_or_else(|| m.split('.').next().unwrap_or(m).to_string())).or_default() += 1;
                }
            }
            St::ImportFrom(_, v) => {
                for (n, a) in v {
                    *out.entry(a.clone().unwrap_or_else(|| n.clone())).or_default() += 1;
                }
            }
            St::With(items, _) => items.iter().filter_map(|(_, t)| t.as_ref()).for_each(|t| targets(t, out)),
            St::Try(_, hs, _, _) => {
                for h in hs {
                    if let Some(n) = &h.name {
                        *out.entry(n.clone()).or_default() += 1;
                    }
                }
            }
            _ => {}
        }
        if !matches!(&s.st, St::Def(_) | St::Class(_)) {
            crate::typed_guard::each_block(&s.st, &mut |b| bound_in(b, out));
        }
    }
}

// The names `:=` binds in a statement's own expressions (not in the bodies it holds).
fn walrus_names(st: &St, f: &mut dyn FnMut(&str)) {
    let mut one = |e: &Ex| {
        crate::typed_guard::walk_ex(e, &mut |x| {
            if let Ex::Walrus(n, _) = x {
                f(n);
            }
        })
    };
    match st {
        St::Expr(e) | St::Return(Some(e)) => one(e),
        St::Assign(ts, v) => {
            ts.iter().for_each(&mut one);
            one(v);
        }
        St::AugAssign(t, _, v) => {
            one(t);
            one(v);
        }
        St::AnnAssign(t, v, a, _) => {
            one(t);
            v.iter().for_each(&mut one);
            one(a);
        }
        St::Raise(a, b) => a.iter().chain(b.iter()).for_each(&mut one),
        St::Assert(a, b) => std::iter::once(a).chain(b.iter()).for_each(&mut one),
        St::If(arms, _) => arms.iter().for_each(|(c, _)| one(c)),
        St::While(c, _, _) => one(c),
        St::For(t, it, _, _) => {
            one(t);
            one(it);
        }
        St::With(items, _) => items.iter().for_each(|(e, t)| {
            one(e);
            t.iter().for_each(&mut one);
        }),
        St::Try(_, hs, _, _) => hs.iter().filter_map(|h| h.types.as_ref()).for_each(&mut one),
        St::Def(d) => {
            d.decorators.iter().for_each(&mut one);
            d.params.pos.iter().chain(d.params.kwonly.iter()).filter_map(|(_, v)| v.as_ref()).for_each(&mut one);
            d.params.ann.iter().for_each(|(_, a)| one(a));
            d.ret.iter().for_each(&mut one);
        }
        St::Class(c) => {
            c.decorators.iter().for_each(&mut one);
            c.bases.iter().for_each(&mut one);
            c.kwargs.iter().for_each(|(_, v)| one(v));
        }
        _ => {}
    }
}

// Names bound in every one of the scopes, each with its kind when all agree (else Other).
fn meet(envs: &[&HashMap<String, K>]) -> HashMap<String, K> {
    let Some((first, rest)) = envs.split_first() else { return HashMap::new() };
    let mut out = HashMap::new();
    for (n, k) in first.iter() {
        if rest.iter().all(|e| e.contains_key(n)) {
            let same = rest.iter().all(|e| e.get(n) == Some(k));
            out.insert(n.clone(), if same { k.clone() } else { K::Other });
        }
    }
    out
}

// A block that ends by leaving (its last statement raises, returns, breaks or continues): its bindings never
// reach the code after the statement that holds it.
fn leaves(body: &[Stmt]) -> bool {
    matches!(body.last().map(|s| &s.st), Some(St::Raise(..) | St::Return(_) | St::Break | St::Continue))
}

fn is_ident(t: &str) -> bool {
    t.chars().next().is_some_and(|c| c.is_alphabetic() || c == '_') && t.chars().all(|c| c.is_alphanumeric() || c == '_')
}

const KEYWORDS: &[&str] = &[
    "False", "None", "True", "and", "as", "assert", "async", "await", "break", "class", "continue", "def", "del", "elif", "else", "except", "finally", "for", "from",
    "global", "if", "import", "in", "is", "lambda", "nonlocal", "not", "or", "pass", "raise", "return", "try", "while", "with", "yield",
];

impl Ctx {
    fn lookup(&self, n: &str, chain: &[Scope]) -> Option<K> {
        // a name some def declares global or nonlocal may be bound, rebound or deleted by any call
        if self.loose.contains(n) {
            return None;
        }
        let last = chain.len() - 1;
        for (i, s) in chain.iter().enumerate().rev() {
            // A class body's names are seen only from that body itself, never from a def or class inside it.
            if s.class && i != last {
                continue;
            }
            if let Some(k) = s.names.get(n) {
                return Some(k.clone());
            }
        }
        let t = tables();
        if t.builtins.contains(n) {
            return Some(Self::std("builtins", n).unwrap_or(K::Other));
        }
        None
    }

    fn std(m: &str, n: &str) -> Option<K> {
        tables().rows.get(&format!("{m} {n}")).map(|&(m, n, _, _)| K::Std(m, n))
    }

    // What `e` holds when CPython evaluates it inside an annotation, or why that could raise.
    fn value(&self, e: &Ex, chain: &[Scope], top: bool) -> Result<K, String> {
        match e {
            Ex::Name(n) => self.lookup(n, chain).ok_or_else(|| format!("the annotation reads `{n}`, which is not bound on every path to where CPython evaluates it")),
            Ex::Attr(b, a) => match self.value(b, chain, false)? {
                K::Module(m) => {
                    let sub = format!("{m}.{a}");
                    if let Some(k) = Self::std(&m, a) {
                        Ok(k)
                    } else if tables().mods.contains(sub.as_str()) {
                        Ok(K::Module(sub))
                    } else {
                        Err(format!("the annotation reads `{m}.{a}`, which Brevi does not know to be a class or typing object of `{m}`"))
                    }
                }
                _ => Err(format!("the annotation reads the attribute `.{a}` of a value Brevi cannot check")),
            },
            Ex::Index(b, i) => {
                let kb = self.value(b, chain, false)?;
                let args: Vec<&Ex> = match i.as_ref() {
                    Ex::Tuple(v) => v.iter().collect(),
                    x => vec![x],
                };
                if let K::Generic(np) = kb {
                    if args.len() != np || matches!(i.as_ref(), Ex::Tuple(v) if v.is_empty()) {
                        return Err(format!("the annotation gives a generic class {} type arguments where it has {np} parameters, which CPython refuses", args.len()));
                    }
                    self.targs(&args, chain)?;
                    return Ok(K::Type);
                }
                let K::Std(m, n) = kb else { return Err("the annotation subscripts a value whose subscript Brevi cannot check as CPython's".into()) };
                let sub = tables().rows[&format!("{m} {n}")].3;
                let tuple = matches!(i.as_ref(), Ex::Tuple(_));
                match sub {
                    "S" => self.special(m, n, &args, tuple, chain, top)?,
                    "*" => self.targs(&args, chain)?,
                    "-" => return Err(format!("the annotation subscripts `{n}`, which CPython cannot subscript")),
                    counts => {
                        if tuple && args.is_empty() || !counts.split(',').any(|c| c.parse() == Ok(args.len())) {
                            return Err(format!("the annotation gives `{n}[...]` {} arguments, which CPython refuses", args.len()));
                        }
                        self.targs(&args, chain)?
                    }
                }
                Ok(K::Type)
            }
            Ex::Bin("|", l, r) => {
                let side = |x: &Ex| -> Result<bool, String> {
                    if matches!(x, Ex::NoneV) {
                        return Ok(false);
                    }
                    if self.value(x, chain, false)?.ors() {
                        Ok(true)
                    } else {
                        Err("the annotation uses `|` on a value Brevi does not know to take it".into())
                    }
                };
                if side(l)? | side(r)? {
                    Ok(K::Type)
                } else {
                    Err("the annotation is `None | None`, which CPython refuses".into())
                }
            }
            Ex::Int(_) | Ex::Float(_) | Ex::Str(_) | Ex::NoneV | Ex::True | Ex::False | Ex::Ellipsis if top => Ok(K::Other),
            Ex::Tuple(v) | Ex::List(v) if top => {
                for x in v {
                    self.value(x, chain, true)?;
                }
                Ok(K::Other)
            }
            _ => Err("the annotation holds an expression Brevi does not check as CPython evaluates it".into()),
        }
    }

    // One argument typing._type_check takes as it is (CPython 3.13).
    fn targ(&self, e: &Ex, chain: &[Scope]) -> Result<(), String> {
        match e {
            Ex::Str(t) => {
                if !t.is_empty() && t.split('.').all(|p| is_ident(p) && !KEYWORDS.contains(&p)) {
                    Ok(())
                } else {
                    Err(format!("the annotation holds the forward reference {t:?}, which Brevi does not check as CPython compiles it"))
                }
            }
            Ex::NoneV | Ex::Int(_) | Ex::Float(_) | Ex::True | Ex::False | Ex::Ellipsis => Ok(()),
            Ex::Unary("-", x) if matches!(x.as_ref(), Ex::Int(_) | Ex::Float(_)) => Ok(()),
            _ => {
                if self.value(e, chain, false)?.arg() {
                    Ok(())
                } else {
                    Err("the annotation passes a typing form a value Brevi does not know it takes".into())
                }
            }
        }
    }

    fn targs(&self, args: &[&Ex], chain: &[Scope]) -> Result<(), String> {
        args.iter().try_for_each(|a| self.targ(a, chain))
    }

    // typing's special forms (and collections.abc.Callable), by name: the ones Brevi checks as CPython 3.13 does.
    fn special(&self, m: &str, n: &str, args: &[&Ex], tuple: bool, chain: &[Scope], top: bool) -> Result<(), String> {
        let bad = |why: &str| Err(format!("the annotation's `{n}[...]` {why}"));
        match n {
            "Union" if !args.is_empty() => self.targs(args, chain),
            "Union" => bad("has no arguments, which CPython refuses"),
            "Optional" if !tuple => self.targs(args, chain),
            "Optional" => bad("has more than one argument, which CPython refuses"),
            "Tuple" if m == "typing" => self.targs(args, chain),
            "ClassVar" | "Final" if m == "typing" && top && !tuple => self.targs(args, chain),
            "ClassVar" | "Final" => bad("is inside another subscript or has more than one argument"),
            "Callable" => {
                if args.len() != 2 || !tuple {
                    return bad("is not Callable[[arg, ...], result], which CPython refuses");
                }
                match args[0] {
                    Ex::Ellipsis => {}
                    Ex::List(v) => v.iter().try_for_each(|a| self.targ(a, chain))?,
                    _ => return bad("does not start with a list of arguments or `...`"),
                }
                self.targ(args[1], chain)
            }
            "Literal" if !args.is_empty() => {
                for a in args {
                    let lit = match a {
                        Ex::Int(_) | Ex::Str(_) | Ex::True | Ex::False | Ex::NoneV => true,
                        Ex::Unary("-", x) => matches!(x.as_ref(), Ex::Int(_)),
                        _ => false,
                    };
                    if !lit {
                        return bad("holds a value that is not a literal Brevi checks");
                    }
                }
                Ok(())
            }
            "Annotated" if tuple && args.len() >= 2 => {
                self.targ(args[0], chain)?;
                for a in &args[1..] {
                    match a {
                        Ex::Int(_) | Ex::Float(_) | Ex::Str(_) | Ex::True | Ex::False | Ex::NoneV | Ex::Ellipsis => {}
                        _ => return bad("holds metadata that is not a constant, which Brevi does not evaluate"),
                    }
                }
                Ok(())
            }
            _ => bad("is a form Brevi does not check as CPython does"),
        }
    }

    fn ann(&self, e: &Ex, chain: &[Scope], line: usize) -> Res {
        self.value(e, chain, true).map(|_| ()).map_err(|w| (line, w))
    }

    // What `v` holds once `x = v` runs.
    fn kind_of(&self, v: &Ex, chain: &[Scope]) -> K {
        if let Ex::Call(f, _) = v {
            return match self.value(f, chain, false) {
                Ok(K::Std("typing", "TypeVar")) => K::TVar,
                Ok(K::Std("typing", "ParamSpec" | "TypeVarTuple" | "NewType")) => K::Type,
                _ => K::Other,
            };
        }
        if matches!(v, Ex::Name(_) | Ex::Attr(..) | Ex::Index(..) | Ex::Bin("|", ..)) {
            if let Ok(k) = self.value(v, chain, false) {
                return k;
            }
        }
        K::Other
    }

    fn class_kind(&self, c: &crate::dynpy::parse::ClassDef, chain: &[Scope]) -> K {
        if !c.kwargs.iter().all(|(k, _)| k == "total") {
            return K::Other;
        }
        // decorators that hand back the class they are given
        let plain_deco = c.decorators.iter().all(|d| {
            let f = if let Ex::Call(f, _) = d { f.as_ref() } else { d };
            let from = match f {
                Ex::Name(n) => match self.lookup(n, chain) {
                    Some(K::From(m, n)) => Some((m, n)),
                    Some(K::Std(m, n)) => Some((m.to_string(), n.to_string())),
                    _ => None,
                },
                Ex::Attr(b, a) => match self.value(b, chain, false) {
                    Ok(K::Module(m)) => Some((m, a.clone())),
                    _ => None,
                },
                _ => None,
            };
            matches!(from.as_ref().map(|(m, n)| (m.as_str(), n.as_str())), Some(("dataclasses", "dataclass") | ("functools", "total_ordering") | ("enum", "unique") | ("typing", "runtime_checkable" | "final")))
        });
        if !plain_deco {
            return K::Other;
        }
        let mut generic = None;
        let mut other_index = false;
        for b in &c.bases {
            if let Ex::Index(h, ps) = b {
                let ps: Vec<&Ex> = match ps.as_ref() {
                    Ex::Tuple(v) => v.iter().collect(),
                    x => vec![x],
                };
                let mut seen = HashSet::new();
                let tvars = !ps.is_empty() && ps.iter().all(|p| matches!(p, Ex::Name(n) if seen.insert(n.clone()) && self.lookup(n, chain) == Some(K::TVar)));
                if generic.is_none() && tvars && matches!(self.value(h, chain, false), Ok(K::Std("typing", "Generic" | "Protocol"))) {
                    generic = Some(ps.len());
                } else {
                    other_index = true;
                }
            }
        }
        let known = c.bases.iter().all(|b| match b {
            Ex::Index(..) => true,
            b => matches!(self.value(b, chain, false), Ok(K::Std("builtins" | "typing" | "collections.abc" | "collections" | "enum" | "abc" | "dataclasses", _) | K::Class)),
        });
        if known && !other_index && generic.is_some() {
            K::Generic(generic.unwrap())
        } else if known {
            K::Class
        } else {
            K::ClassU
        }
    }

    fn bind_target(t: &Ex, k: K, s: &mut Scope) {
        match t {
            Ex::Name(n) => {
                s.names.insert(n.clone(), k);
            }
            Ex::Tuple(v) | Ex::List(v) => v.iter().for_each(|x| Self::bind_target(x, K::Other, s)),
            Ex::Star(x) => Self::bind_target(x, K::Other, s),
            _ => {}
        }
    }

    // Names the innermost scope rebinds in `body` lose what was known of them (a loop's next pass, an
    // exception raised part way through).
    fn loosen(body: &[Stmt], s: &mut Scope) {
        let mut b = HashMap::new();
        bound_in(body, &mut b);
        for n in b.keys() {
            if let Some(k) = s.names.get_mut(n) {
                *k = K::Other;
            }
        }
    }

    fn sub_block(&self, body: &[Stmt], chain: &mut Vec<Scope>, w: Where, start: HashMap<String, K>) -> Result<HashMap<String, K>, (usize, String)> {
        let saved = std::mem::replace(&mut chain.last_mut().unwrap().names, start);
        let r = self.block(body, chain, w);
        let end = std::mem::replace(&mut chain.last_mut().unwrap().names, saved);
        r.map(|_| end)
    }

    fn def(&self, d: &FuncDef, chain: &mut Vec<Scope>, line: usize) -> Res {
        // The def's own annotations, evaluated where the def runs (PEP 695 `def f[T]` sees its T).
        let mut tp = Scope::default();
        for t in &d.tparams {
            tp.names.insert(t.clone(), K::TVar);
        }
        let own: Vec<&Ex> = d.params.ann.iter().map(|(_, a)| a).chain(d.ret.iter()).collect();
        if !own.is_empty() {
            let pushed = !tp.names.is_empty();
            if pushed {
                chain.push(tp.clone());
            }
            let r = own.iter().try_for_each(|a| self.ann(a, chain, d.line.max(line)));
            if pushed {
                chain.pop();
            }
            r?;
        }
        // Its body runs later, at a call: only annotations of the defs and classes inside it are evaluated, and
        // of the names around it, only the ones bound once in their scope keep what is known of them.
        let mut has_nested = false;
        scan_all(&d.body, &mut |st| has_nested |= matches!(st, St::Def(_) | St::Class(_)));
        if !has_nested {
            return Ok(());
        }
        let mut inner: Vec<Scope> = Vec::new();
        for s in chain.iter().filter(|s| !s.class) {
            inner.push(s.clone());
        }
        for s in inner.iter_mut() {
            for (n, k) in s.names.iter_mut() {
                if s.counts.get(n).copied().unwrap_or(0) > 1 {
                    *k = K::Other;
                }
            }
        }
        if !tp.names.is_empty() {
            inner.push(tp);
        }
        let mut locals = HashMap::new();
        bound_in(&d.body, &mut locals);
        let mut me = Scope::default();
        let p = &d.params;
        for n in p.pos.iter().chain(p.kwonly.iter()).map(|(n, _)| n).chain(p.star.iter()).chain(p.kwstar.iter()) {
            *locals.entry(n.clone()).or_default() += 1;
            me.names.insert(n.clone(), K::Other);
        }
        me.counts = locals.clone();
        // A name the body binds is local in all of it: the outer one is not seen, even before the binding.
        for s in inner.iter_mut() {
            s.names.retain(|n, _| !locals.contains_key(n));
        }
        inner.push(me);
        self.block(&d.body, &mut inner, Where::Func)
    }

    fn block(&self, body: &[Stmt], chain: &mut Vec<Scope>, w: Where) -> Res {
        for s in body {
            let line = s.line;
            let mut walrus = vec![];
            walrus_names(&s.st, &mut |n| walrus.push(n.to_string()));
            match &s.st {
                St::AnnAssign(t, v, a, _) => {
                    if w != Where::Func {
                        self.ann(a, chain, line)?;
                    }
                    if let Some(v) = v {
                        let k = self.kind_of(v, chain);
                        Self::bind_target(t, k, chain.last_mut().unwrap());
                    }
                }
                St::Assign(ts, v) => {
                    let k = if ts.len() == 1 { self.kind_of(v, chain) } else { K::Other };
                    for t in ts {
                        Self::bind_target(t, k.clone(), chain.last_mut().unwrap());
                    }
                }
                St::AugAssign(t, _, _) => Self::bind_target(t, K::Other, chain.last_mut().unwrap()),
                St::Def(d) => {
                    self.def(d, chain, line)?;
                    chain.last_mut().unwrap().names.insert(d.name.clone(), K::Other);
                }
                St::Class(c) => {
                    chain.push(Scope { names: HashMap::new(), class: true, counts: HashMap::new() });
                    let r = self.block(&c.body, chain, Where::Class);
                    chain.pop();
                    r?;
                    let k = self.class_kind(c, chain);
                    chain.last_mut().unwrap().names.insert(c.name.clone(), k);
                }
                St::Import(v) => {
                    for (m, a) in v {
                        let (n, k) = match a {
                            Some(a) => (a.clone(), K::Module(m.clone())),
                            None => {
                                let top = m.split('.').next().unwrap_or(m).to_string();
                                (top.clone(), K::Module(top))
                            }
                        };
                        let known = matches!(&k, K::Module(m) if tables().mods.contains(m.as_str()));
                        chain.last_mut().unwrap().names.insert(n, if known { k } else { K::Other });
                    }
                }
                St::ImportFrom(m, v) => {
                    for (n, a) in v {
                        if n == "*" {
                            continue;
                        }
                        let sub = format!("{m}.{n}");
                        let k = Self::std(m, n).unwrap_or(if tables().mods.contains(sub.as_str()) { K::Module(sub) } else { K::From(m.clone(), n.clone()) });
                        chain.last_mut().unwrap().names.insert(a.clone().unwrap_or_else(|| n.clone()), k);
                    }
                }
                St::Del(v) => {
                    for t in v {
                        if let Ex::Name(n) = t {
                            chain.last_mut().unwrap().names.remove(n);
                        }
                    }
                }
                St::If(arms, els) => {
                    let before = chain.last().unwrap().names.clone();
                    let mut ends = vec![];
                    for (_, b) in arms {
                        let e = self.sub_block(b, chain, w, before.clone())?;
                        if !leaves(b) {
                            ends.push(e);
                        }
                    }
                    match els {
                        Some(b) => {
                            let e = self.sub_block(b, chain, w, before.clone())?;
                            if !leaves(b) {
                                ends.push(e);
                            }
                        }
                        None => ends.push(before.clone()),
                    }
                    let refs: Vec<&HashMap<String, K>> = ends.iter().collect();
                    chain.last_mut().unwrap().names = if refs.is_empty() { before } else { meet(&refs) };
                }
                St::For(_, _, b, els) | St::While(_, b, els) => {
                    let mut start = chain.last().unwrap().clone();
                    Self::loosen(b, &mut start);
                    if let Some(e) = els {
                        Self::loosen(e, &mut start);
                    }
                    let mut inside = start.names.clone();
                    if let St::For(t, ..) = &s.st {
                        let mut tmp = Scope { names: inside, ..Default::default() };
                        Self::bind_target(t, K::Other, &mut tmp);
                        inside = tmp.names;
                    }
                    let end = self.sub_block(b, chain, w, inside)?;
                    let mut ends = vec![start.names.clone(), end];
                    if let Some(e) = els {
                        let after = meet(&[&ends[0], &ends[1]]);
                        ends.push(self.sub_block(e, chain, w, after)?);
                    }
                    let refs: Vec<&HashMap<String, K>> = ends.iter().collect();
                    chain.last_mut().unwrap().names = meet(&refs);
                }
                St::With(items, b) => {
                    let mut start = chain.last().unwrap().clone();
                    for (_, t) in items {
                        if let Some(t) = t {
                            Self::bind_target(t, K::Other, &mut start);
                        }
                    }
                    // __exit__ may swallow an exception raised part way through the body.
                    let mut loose = start.clone();
                    Self::loosen(b, &mut loose);
                    let end = self.sub_block(b, chain, w, start.names.clone())?;
                    chain.last_mut().unwrap().names = meet(&[&loose.names, &end]);
                }
                St::Try(b, hs, els, fin) => {
                    let before = chain.last().unwrap().clone();
                    let mut caught = before.clone();
                    Self::loosen(b, &mut caught);
                    let mut end = self.sub_block(b, chain, w, before.names.clone())?;
                    if let Some(e) = els {
                        end = self.sub_block(e, chain, w, end)?;
                    }
                    let mut ends = vec![end];
                    for h in hs {
                        let mut start = caught.clone();
                        if let Some(n) = &h.name {
                            start.names.insert(n.clone(), K::Other);
                        }
                        let mut e = self.sub_block(&h.body, chain, w, start.names)?;
                        if let Some(n) = &h.name {
                            e.remove(n);
                        }
                        if !leaves(&h.body) {
                            ends.push(e);
                        }
                    }
                    let refs: Vec<&HashMap<String, K>> = ends.iter().collect();
                    let merged = meet(&refs);
                    match fin {
                        Some(f) => {
                            let fstart = meet(&[&caught.names, &merged]);
                            let fend = self.sub_block(f, chain, w, fstart.clone())?;
                            let mut out = merged;
                            for (n, k) in &fend {
                                if fstart.get(n) != Some(k) {
                                    out.insert(n.clone(), k.clone());
                                }
                            }
                            out.retain(|n, _| fend.contains_key(n) || !fstart.contains_key(n));
                            chain.last_mut().unwrap().names = out;
                        }
                        None => chain.last_mut().unwrap().names = merged,
                    }
                }
                _ => {}
            }
            for n in walrus {
                chain.last_mut().unwrap().names.insert(n, K::Other);
            }
        }
        Ok(())
    }
}

#[cfg(test)]
mod tests {
    fn why(src: &str) -> Option<String> {
        super::check(&crate::dynpy::parse::parse(src).unwrap()).map(|(_, w)| w)
    }

    #[test]
    fn forward_and_self_references_leave() {
        assert!(why("def f(a: Later):\n    pass\nclass Later:\n    pass\nprint(1)\n").is_some());
        assert!(why("class Vec:\n    def add(self, o: Vec) -> Vec:\n        return self\nprint(1)\n").is_some());
        assert!(why("class C:\n    x: C\n").is_some());
        assert!(why("x: Missing = 1\n").is_some());
        assert!(why("if a():\n    class A: pass\ndef f(x: A): pass\n").is_some());
        assert!(why("try:\n    import json\n    class A: pass\nexcept ImportError:\n    pass\ndef f(x: A): pass\n").is_some());
    }

    #[test]
    fn subscripts_cpython_refuses_leave() {
        for a in ["Callable[int]", "Union[()]", "int[str]", "Dict[str]", "Optional[int, str]", "List[Union]", "\"x\" | int", "None | None", "List[\"a b\"]", "f()"] {
            let src = format!("from typing import *\nfrom typing import Callable, Union, Dict, Optional, List\ndef f(a: {a}): pass\n");
            assert!(why(&src).is_some(), "{a}");
        }
    }

    #[test]
    fn ordinary_annotations_stay_typed() {
        assert_eq!(why("from typing import Generic, TypeVar\nT = TypeVar('T')\nclass S(Generic[T]):\n    pass\nx: S[int] = S()\n"), None);
        assert!(why("from typing import Generic, TypeVar\nT = TypeVar('T')\nclass S(Generic[T]):\n    pass\nx: S[int, str] = S()\n").is_some());
        let src = "from typing import List, Dict, Optional, Callable, Union, Tuple, TypeVar\nimport typing as t\nfrom dataclasses import dataclass\nfrom collections import deque\nT = TypeVar('T')\n\
                   class Point:\n    x: int\n    y: 'Point'\n    def near(self, o: 'Point') -> bool:\n        return True\n\
                   @dataclass\nclass Box:\n    items: List[Point]\n    tag: Optional[str] = None\n\
                   def f(a: int, b: list[int] | None = None, *r: str, **k: Dict[str, Tuple[int, ...]]) -> Callable[[int], Point]:\n    def g(x: int) -> int:\n        return x\n    return g\n\
                   def h(q: deque[int], u: Union[int, str], v: t.List[T], w: Point | None) -> T: pass\nN: int = 3\n";
        assert_eq!(why(src), None);
        assert_eq!(why("from __future__ import annotations\ndef f(a: Later): pass\n"), None);
        assert_eq!(why("print(1)\n"), None);
    }
}
