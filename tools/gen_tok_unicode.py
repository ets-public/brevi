"""Writes src/dynpy/rt_tokuni.rs: the Unicode classes of tiktoken's split patterns, read off tiktoken itself.

tiktoken splits text with the Rust regex crate (through fancy-regex), whose Unicode version is not CPython's
unicodedata's. So each class is probed: an Encoding whose pattern is just the class, run over every code point,
gives back exactly the code points the class matches. Run with the tiktoken version Brevi's copy follows:
    python3 tools/gen_tok_unicode.py
"""
import os
import sys

import tiktoken

CLASSES = ["L", "Lu", "Ll", "Lt", "Lm", "Lo", "M", "Mn", "Mc", "Me", "N", "Nd", "Nl", "No", "P", "S", "Z"]
EXTRA = {"SPACE": r"\s", "WORD": r"\w"}

ranks = {bytes([i]): i for i in range(256)}
text = "".join(chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000)


def members(pat):
    e = tiktoken.Encoding("probe", pat_str=pat, mergeable_ranks=ranks, special_tokens={})
    return bytes(e.encode_ordinary(text)).decode()


def ranges(chars):
    out = []
    for c in sorted(ord(x) for x in chars):
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def main():
    lines = [
        "// Generated by tools/gen_tok_unicode.py from tiktoken " + tiktoken.__version__ + ": do not edit.",
        "// The code points of each Unicode class as tiktoken's regex (Rust regex crate) sees them, as ranges.",
    ]
    names = [(c, r"\p{" + c + "}") for c in CLASSES] + list(EXTRA.items())
    for name, pat in names:
        rs = ranges(members(pat))
        body = ",".join(f"(0x{a:x},0x{b:x})" for a, b in rs)
        lines.append(f"pub const TU_{name.upper()}: &[(u32, u32)] = &[{body}];")
    # (?i): the characters outside ASCII that a letter's case-insensitive match takes in
    fold = {}
    for c in "abcdefghijklmnopqrstuvwxyz":
        extra = [x for x in members(f"(?i:{c})") if x not in (c, c.upper())]
        if extra:
            fold[c] = extra
    body = ",".join(f"('{c}','\\u{{{ord(x):x}}}')" for c, xs in fold.items() for x in xs)
    lines.append(f"pub const TU_FOLD: &[(char, char)] = &[{body}];")
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "dynpy", "rt_tokuni.rs")
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("wrote", os.path.normpath(out), file=sys.stderr)


main()
