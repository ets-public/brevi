"""Writes src/dynpy/rt_hfcls.rs: the character tests Hugging Face tokenizers makes, read from tokenizers itself.

tokenizers (Rust) asks char::is_whitespace, char::is_numeric, char::to_lowercase (the Unicode of the Rust it was
built with), the unicode_categories crate (punctuation, "other", non-spacing marks), unicode-normalization-
alignments (combining marks) and the regex crate (\\w and \\s, for the Whitespace pre-tokenizer and single-word
added tokens). None of these is CPython's unicodedata, so this asks the installed tokenizers, code point by code
point, through the components that use each test:
    pip install tokenizers==0.23.3 && python3 tools/gen_hf_chars.py
"""
import os

import tokenizers
from tokenizers import normalizers as N, pre_tokenizers as P

assert tokenizers.__version__ == "0.23.3", tokenizers.__version__

ws_split = P.WhitespaceSplit()
digits = P.Digits(individual_digits=True)
punct = P.Punctuation()
white = P.Whitespace()
clean = N.BertNormalizer(clean_text=True, handle_chinese_chars=False, strip_accents=False, lowercase=False)
accents = N.BertNormalizer(clean_text=False, handle_chinese_chars=False, strip_accents=True, lowercase=False)
nfd = N.NFD()
strip_acc = N.StripAccents()
lower = N.Lowercase()

sets = {k: [] for k in ("HC_WS", "HC_NUM", "HC_PUNCT", "HC_OTHER", "HC_MN", "HC_COMB", "HC_REW", "HC_RES")}
lows = []
for c in range(0x110000):
    if 0xD800 <= c <= 0xDFFF:
        continue
    ch = chr(c)
    s = "a" + ch + "a"
    if len(ws_split.pre_tokenize_str(s)) == 2:
        sets["HC_WS"].append(c)
    if len(digits.pre_tokenize_str(s)) == 3:
        sets["HC_NUM"].append(c)
    if len(punct.pre_tokenize_str(s)) == 3:
        sets["HC_PUNCT"].append(c)
    if c not in (0, 0xFFFD, 9, 10, 13) and clean.normalize_str(ch) == "":
        sets["HC_OTHER"].append(c)
    if nfd.normalize_str(ch) == ch and accents.normalize_str(ch) == "":
        sets["HC_MN"].append(c)
    if strip_acc.normalize_str(ch) == "":
        sets["HC_COMB"].append(c)
    w = [t for t, _ in white.pre_tokenize_str("a" + ch)]
    if w == ["a" + ch]:
        sets["HC_REW"].append(c)
    elif w == ["a"]:
        sets["HC_RES"].append(c)
    lo = lower.normalize_str(ch)
    if lo != ch:
        lows.append((c, lo))


def ranges(cs):
    out = []
    for c in cs:
        if out and out[-1][1] == c - 1:
            out[-1][1] = c
        else:
            out.append([c, c])
    return out


def rs_str(s):
    return '"' + "".join(f"\\u{{{ord(x):x}}}" for x in s) + '"'


lines = ["// Generated by tools/gen_hf_chars.py from tokenizers 0.23.3 itself: do not edit.", ""]
for k, cs in sets.items():
    rs = ranges(cs)
    lines.append(f"pub static {k}: [(u32, u32); {len(rs)}] = [")
    for i in range(0, len(rs), 8):
        lines.append("    " + " ".join(f"({a:#x}, {b:#x})," for a, b in rs[i:i + 8]))
    lines.append("];")
lines.append(f"pub static HC_LOWER: [(u32, &str); {len(lows)}] = [")
for i in range(0, len(lows), 6):
    lines.append("    " + " ".join(f"({c:#x}, {rs_str(lo)})," for c, lo in lows[i:i + 6]))
lines.append("];")
out = os.path.join(os.path.dirname(__file__), "..", "src", "dynpy", "rt_hfcls.rs")
open(out, "w").write("\n".join(lines) + "\n")
print({k: len(v) for k, v in sets.items()}, "lower", len(lows))
