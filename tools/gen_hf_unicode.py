"""Writes src/dynpy/rt_hfuni.rs: the Unicode normalization data Hugging Face tokenizers normalizes with.

tokenizers runs NFC/NFD/NFKC/NFKD through the crate unicode-normalization-alignments 0.1.12 (MIT/Apache-2.0),
whose tables are Unicode 9.0, not CPython's unicodedata. This reads that crate's src/tables.rs and writes the
same data as sorted arrays:
    curl -sSL -o u.crate https://static.crates.io/crates/unicode-normalization-alignments/unicode-normalization-alignments-0.1.12.crate
    tar xzf u.crate && python3 tools/gen_hf_unicode.py unicode-normalization-alignments-0.1.12/src/tables.rs
"""
import os
import re
import sys

src = open(sys.argv[1]).read()


def block(name):
    at = src.index(f"const {name}")
    return src[at:src.index("];", at)]


ccc = sorted((int(x, 16) >> 8, int(x, 16) & 0xFF) for x in re.findall(r"0x([0-9A-Fa-f]+),", block("CANONICAL_COMBINING_CLASS_KV")))
comp = []
for k, r in re.findall(r"\(0x([0-9A-Fa-f]+), '\\u\{([0-9A-Fa-f]+)\}'\)", block("COMPOSITION_TABLE_KV")):
    k = int(k, 16)
    comp.append((k >> 16, k & 0xFFFF, int(r, 16)))
astral = src[src.index("fn composition_table_astral"):]
astral = astral[:astral.index("_ => None")]
for a, b, r in re.findall(r"\('\\u\{([0-9A-Fa-f]+)\}', '\\u\{([0-9A-Fa-f]+)\}'\) => Some\('\\u\{([0-9A-Fa-f]+)\}'\)", astral):
    comp.append((int(a, 16), int(b, 16), int(r, 16)))
comp.sort()


def decomp(name):
    out = []
    for k, chars in re.findall(r"\(0x([0-9A-Fa-f]+), &\[([^\]]*)\]\)", block(name)):
        out.append((int(k, 16), [int(c, 16) for c in re.findall(r"\\u\{([0-9A-Fa-f]+)\}", chars)]))
    return sorted(out)


canon = decomp("CANONICAL_DECOMPOSED_KV")
compat = decomp("COMPATIBILITY_DECOMPOSED_KV")


def chars(cs):
    return "&[" + ",".join(f"'\\u{{{c:x}}}'" for c in cs) + "]"


lines = [
    "// Generated by tools/gen_hf_unicode.py from unicode-normalization-alignments 0.1.12 (Unicode 9.0, MIT/Apache-2.0): do not edit.",
    "pub const HU_CCC: &[(u32, u8)] = &[" + ",".join(f"(0x{a:x},{b})" for a, b in ccc) + "];",
    "pub const HU_COMP: &[(u32, u32, u32)] = &[" + ",".join(f"(0x{a:x},0x{b:x},0x{r:x})" for a, b, r in comp) + "];",
    "pub const HU_CANON: &[(u32, &[char])] = &[" + ",".join(f"(0x{k:x},{chars(v)})" for k, v in canon) + "];",
    "pub const HU_COMPAT: &[(u32, &[char])] = &[" + ",".join(f"(0x{k:x},{chars(v)})" for k, v in compat) + "];",
]
out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "dynpy", "rt_hfuni.rs")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", os.path.normpath(out), len(ccc), len(comp), len(canon), len(compat), file=sys.stderr)
