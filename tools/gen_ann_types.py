#!/usr/bin/env python3
"""Writes src/pynames/ann_types.txt: what CPython 3.13 lets an evaluated annotation do with each class or typing
object a stdlib module (src/pynames/mods.txt, plus builtins and collections.abc) exports. Read by
src/typed_guard.rs (annotations), which sends a file to the dynamic build when an annotation it evaluates could
raise. One line per name: `module name flags sub`.
  flags: o = `x | int` works, a = `typing.List[x]` takes it, - = neither
  sub:   - = x[...] raises, * = any number of type arguments (types.GenericAlias), S = a special form typed_guard
         handles by name (or refuses), else the comma-separated counts of `int` arguments (1 to 4) it takes.
Run with python3.13: python3 tools/gen_ann_types.py > src/pynames/ann_types.txt
"""
import builtins, importlib, os, sys, typing

assert sys.version_info[:2] == (3, 13), "generate with CPython 3.13"
here = os.path.dirname(os.path.abspath(__file__))
mods = open(os.path.join(here, "..", "src", "pynames", "mods.txt")).read().split()
mods = ["builtins", "collections.abc"] + [m for m in mods if m not in ("tkinter",)]
SPECIAL = {"Union", "Optional", "Callable", "Literal", "Annotated", "ClassVar", "Final", "Tuple", "Concatenate", "TypeGuard",
           "TypeIs", "Required", "NotRequired", "ReadOnly", "Unpack", "Generic", "Protocol"}


def ok(f):
    try:
        f()
        return True
    except BaseException:
        return False


print("# Generated by tools/gen_ann_types.py from CPython %d.%d.%d: do not edit." % sys.version_info[:3])
for m in mods:
    try:
        mod = importlib.import_module(m)
    except BaseException:
        continue
    for n in sorted(vars(mod)):
        if n.startswith("_"):
            continue
        x = getattr(mod, n)
        is_typing = m in ("typing", "collections.abc") or type(x).__module__ == "typing"
        if not (isinstance(x, type) or is_typing):
            continue
        fl = ("o" if ok(lambda: x | int) else "") + ("a" if ok(lambda: typing.List[x]) else "") or "-"
        if (m == "typing" and n in SPECIAL) or (m == "collections.abc" and n == "Callable") or (m == "builtins" and n == "tuple"):
            sub = "S" if n != "tuple" else "*"
        else:
            counts = [k for k in range(1, 5) if ok(lambda: x[(int,) * k if k > 1 else int])]
            sub = "*" if counts == [1, 2, 3, 4] else ",".join(map(str, counts)) or "-"
        print(m, n, fl, sub)
